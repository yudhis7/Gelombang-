// Release signing: CI passes the key through environment variables; a local build can use
// android/keystore.properties (storeFile, storePassword, keyAlias, keyPassword).
// Without either, the release APK is signed with the debug key so it still installs.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(env: String, prop: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: keystoreProps.getProperty(prop)?.takeIf { it.isNotBlank() }

